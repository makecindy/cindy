function bashBoundedBracePatterns(pattern: string): string[] | null {
  const pending = [pattern];
  const expanded: string[] = [];
  while (pending.length > 0) {
    if (pending.length + expanded.length > BASH_REDIRECT_GLOB_MAX_BRACE_PATTERNS) return null;
    const candidate = pending.pop()!;
    const brace = /^(.*?)\{([^{}]+)\}(.*)$/.exec(candidate);
    if (!brace) {
      expanded.push(candidate);
      continue;
    }
    if (!brace[2].includes(',')) return null;
    for (const alternative of brace[2].split(',')) {
      pending.push(brace[1] + alternative + brace[3]);
    }
  }
  return expanded;
}

// node:fs globSync materializes its full result. Walk the broadest possible scope
// with Dir.readSync first so both traversal and the eventual result stay bounded.
function bashGlobTraversalWithinBudget(
  pattern: string,
  cwd: string,
  budget: BashGlobBudget,
): boolean {
  const magicIndex = pattern.search(/[?*\[\]{}()]/);
  if (magicIndex < 0) return true;
  const prefix = pattern.slice(0, magicIndex);
  const separator = Math.max(prefix.lastIndexOf('/'), prefix.lastIndexOf('\\'));
  const rootText = separator >= 0 ? prefix.slice(0, separator + 1) : '.';
  const root = path.isAbsolute(rootText) ? path.resolve(rootText) : path.resolve(cwd, rootText);
  const remaining = pattern.slice(separator + 1).split(/[\\/]/).filter(Boolean);
  if (remaining.length > BASH_REDIRECT_GLOB_MAX_DEPTH) return false;
  const recursive = remaining.some((segment) => segment.includes('**'));
  const maxDepth = recursive ? BASH_REDIRECT_GLOB_MAX_DEPTH : Math.max(1, remaining.length);
  const pending = [{ directory: root, depth: 0 }];

  while (pending.length > 0) {
    const current = pending.pop()!;
    if (budget.workRemaining-- <= 0) return false;
    let directory;
    try {
      directory = opendirSync(current.directory);
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code;
      if (code === 'ENOENT' || code === 'ENOTDIR') continue;
      return false;
    }
    try {
      let entry;
      while ((entry = directory.readSync()) !== null) {
        if (budget.workRemaining-- <= 0) return false;
        const entryPath = path.join(current.directory, entry.name);
        let isDirectory = entry.isDirectory();
        if (!isDirectory && entry.isSymbolicLink()) {
          if (budget.workRemaining-- <= 0) return false;
          try {
            isDirectory = statSync(entryPath).isDirectory();
          } catch {
            return false;
          }
        }
        if (!isDirectory) continue;
        const nextDepth = current.depth + 1;
        if (recursive && nextDepth >= BASH_REDIRECT_GLOB_MAX_DEPTH) return false;
        if (nextDepth >= maxDepth) continue;
        pending.push({ directory: entryPath, depth: nextDepth });
      }
    } finally {
      directory.closeSync();
    }
  }
  return true;
}

