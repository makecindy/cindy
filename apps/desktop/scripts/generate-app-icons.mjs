#!/usr/bin/env node
/**
 * generate-app-icons.mjs — derive every app icon rendition from the shared
 * source in packages/maker-shared/app-icons (manifest.json + 1024px artwork).
 *
 *   - Desktop: apps/desktop/resources/app-icons/<artwork>.png, 512px with the
 *     Apple icon grid baked in (same geometry as generate-mac-icns.mjs),
 *     because `app.dock.setIcon` shows images as-is.
 *   - Mobile: apps/mobile/assets/app-icons/<artwork>.png, small full-bleed
 *     previews for the settings page, plus the generated require map. The iOS
 *     icons themselves are written by plugins/with-app-icons.js at prebuild,
 *     straight from the shared artwork.
 *   - Shared: packages/maker-shared/src/appIcons.generated.ts, the typed list.
 *
 * Usage (from the repository root): pnpm generate:app-icons [--check]
 *
 * `--check` does not render images, so it gives the same answer on every
 * platform: it compares the sources with the hashes recorded by the last run
 * and the outputs on disk with what that run wrote.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');

const SOURCE_DIR = 'packages/maker-shared/app-icons';
const MANIFEST = `${SOURCE_DIR}/manifest.json`;
const RECORD = `${SOURCE_DIR}/generated.json`;
const SHARED_TS = 'packages/maker-shared/src/appIcons.generated.ts';
const DESKTOP_DIR = 'apps/desktop/resources/app-icons';
const MOBILE_DIR = 'apps/mobile/assets/app-icons';
const MOBILE_TS = 'apps/mobile/src/settings/appIconPreviews.generated.ts';
/** The icon Mobile ships with; only its settings preview is derived here. */
const MOBILE_DEFAULT_ICON = 'apps/mobile/assets/icon.png';
const MOBILE_DEFAULT_PREVIEW = 'default';

const MASTER_SIZE = 1024;
// Apple Big Sur+ icon grid on a 1024 canvas, as in generate-mac-icns.mjs.
const GRID_CONTENT = 824;
const GRID_RADIUS = 185.4;
const DOCK_SIZE = 512;
// Largest settings tile is 60pt; 180px covers @3x.
const PREVIEW_SIZE = 180;

const HEADER =
  '// Generated by `pnpm generate:app-icons` from packages/maker-shared/app-icons/manifest.json.\n' +
  '// Do not edit: change the manifest or artwork and run the command again.\n';

const sha256 = (data) => crypto.createHash('sha256').update(data).digest('hex');
/** Text is hashed and compared with LF so Windows checkouts agree. */
const lf = (text) => text.replace(/\r\n/g, '\n');
const read = (root, file) => fs.readFileSync(path.join(root, file));
const readSourceHash = (root, file) =>
  sha256(file.endsWith('.png') ? read(root, file) : lf(read(root, file).toString('utf8')));

/** Parse and validate the manifest; returns icons with artwork stems. */
export function readAppIconManifest(root = repoRoot) {
  const manifest = JSON.parse(read(root, MANIFEST).toString('utf8'));
  if (!Array.isArray(manifest.icons) || manifest.icons.length === 0) {
    throw new Error(`${MANIFEST}: "icons" must be a non-empty list`);
  }
  const ids = new Set();
  const stems = new Map();
  const icons = manifest.icons.map((entry, index) => {
    const id = entry?.id;
    if (typeof id !== 'string' || !/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(id)) {
      throw new Error(`${MANIFEST}: icon ${index} needs a lowercase id such as "night-cat"`);
    }
    if (ids.has(id)) throw new Error(`${MANIFEST}: duplicate id "${id}"`);
    ids.add(id);
    if (entry.artwork == null) return { id, light: null, dark: null };
    const { light, dark } = entry.artwork;
    const stem = (file, mode) => {
      if (typeof file !== 'string' || !/^[a-z0-9][a-z0-9-]*\.png$/.test(file)) {
        throw new Error(`${MANIFEST}: "${id}" ${mode} artwork must be a lowercase .png file name`);
      }
      if (!fs.existsSync(path.join(root, SOURCE_DIR, file))) {
        throw new Error(`${MANIFEST}: "${id}" ${mode} artwork ${file} is missing from ${SOURCE_DIR}`);
      }
      const name = file.slice(0, -'.png'.length);
      if (name === MOBILE_DEFAULT_PREVIEW) {
        throw new Error(`${MANIFEST}: ${file} is reserved for the built-in icon preview`);
      }
      const owner = stems.get(name);
      if (owner && owner !== id) throw new Error(`${MANIFEST}: ${file} is used by "${owner}" and "${id}"`);
      stems.set(name, id);
      return name;
    };
    const lightStem = stem(light, 'light');
    return { id, light: lightStem, dark: dark == null ? lightStem : stem(dark, 'dark') };
  });
  if (icons[0].light !== null) {
    throw new Error(`${MANIFEST}: the first icon is the built-in one and takes no artwork`);
  }
  if (icons.slice(1).some((icon) => icon.light === null)) {
    throw new Error(`${MANIFEST}: only the first icon may omit artwork`);
  }
  return icons;
}

const artworkStems = (icons) => [...new Set(icons.flatMap((icon) => [icon.light, icon.dark]).filter(Boolean))];

function sharedSource(icons) {
  const artwork = icons
    .map((icon) =>
      icon.light === null
        ? `  ${JSON.stringify(icon.id)}: null,`
        : `  ${JSON.stringify(icon.id)}: { light: ${JSON.stringify(icon.light)}, dark: ${JSON.stringify(icon.dark)} },`,
    )
    .join('\n');
  return (
    `${HEADER}\n` +
    `/** Choices in display order; the first is the icon each platform ships with. */\n` +
    `export const APP_ICONS = [${icons.map((icon) => JSON.stringify(icon.id)).join(', ')}] as const;\n\n` +
    `/** Artwork file names (without .png) per mode; null is the built-in icon. */\n` +
    `export const APP_ICON_ARTWORK = {\n${artwork}\n} as const;\n`
  );
}

function mobileSource(icons) {
  const asset = (stem) => `require("../../assets/app-icons/${stem ?? MOBILE_DEFAULT_PREVIEW}.png")`;
  const rows = icons
    .map((icon) => `  ${JSON.stringify(icon.id)}: { light: ${asset(icon.light)}, dark: ${asset(icon.dark)} },`)
    .join('\n');
  return (
    `${HEADER}\n` +
    `import type { ImageSourcePropType } from "react-native";\n` +
    `import type { AppIcon } from "@cindy/maker-shared";\n\n` +
    `/** Settings previews; iOS takes the real icons from the native build. */\n` +
    `export const APP_ICON_PREVIEWS: Record<\n  AppIcon,\n  { light: ImageSourcePropType; dark: ImageSourcePropType }\n> = {\n${rows}\n};\n`
  );
}

function sourceFiles(icons) {
  return [MANIFEST, ...artworkStems(icons).map((stem) => `${SOURCE_DIR}/${stem}.png`), MOBILE_DEFAULT_ICON];
}

function imageOutputs(icons) {
  const stems = artworkStems(icons);
  return [
    ...stems.map((stem) => ({ file: `${DESKTOP_DIR}/${stem}.png`, kind: 'dock', source: `${SOURCE_DIR}/${stem}.png` })),
    ...stems.map((stem) => ({ file: `${MOBILE_DIR}/${stem}.png`, kind: 'preview', source: `${SOURCE_DIR}/${stem}.png` })),
    { file: `${MOBILE_DIR}/${MOBILE_DEFAULT_PREVIEW}.png`, kind: 'preview', source: MOBILE_DEFAULT_ICON },
  ];
}

const textOutputs = (icons) => [
  { file: SHARED_TS, text: sharedSource(icons) },
  { file: MOBILE_TS, text: mobileSource(icons) },
];

function stalePngs(root, icons) {
  const expected = new Set(imageOutputs(icons).map((output) => output.file));
  return [DESKTOP_DIR, MOBILE_DIR].flatMap((dir) =>
    fs.existsSync(path.join(root, dir))
      ? fs
          .readdirSync(path.join(root, dir))
          .filter((name) => name.endsWith('.png'))
          .map((name) => `${dir}/${name}`)
          .filter((file) => !expected.has(file))
      : [],
  );
}

/** Problems that mean `pnpm generate:app-icons` must be run again. */
export function checkAppIcons(root = repoRoot) {
  const problems = [];
  const icons = readAppIconManifest(root);
  let record;
  try {
    record = JSON.parse(read(root, RECORD).toString('utf8'));
  } catch {
    return [`${RECORD} is missing or unreadable`];
  }
  const sources = sourceFiles(icons);
  for (const file of sources) {
    if (record.sources?.[file] !== readSourceHash(root, file)) problems.push(`${file} changed since the last run`);
  }
  for (const file of Object.keys(record.sources ?? {})) {
    if (!sources.includes(file)) problems.push(`${file} is recorded but no longer a source`);
  }
  for (const { file, text } of textOutputs(icons)) {
    const current = fs.existsSync(path.join(root, file)) ? lf(read(root, file).toString('utf8')) : null;
    if (current !== text) problems.push(`${file} is out of date`);
  }
  for (const { file } of imageOutputs(icons)) {
    if (!fs.existsSync(path.join(root, file))) problems.push(`${file} is missing`);
    else if (record.outputs?.[file] !== sha256(read(root, file))) problems.push(`${file} was not written by the last run`);
  }
  for (const file of stalePngs(root, icons)) problems.push(`${file} is not in the manifest`);
  return problems;
}

async function generate(root) {
  const { default: sharp } = await import('sharp');
  const icons = readAppIconManifest(root);

  for (const stem of artworkStems(icons)) {
    const file = `${SOURCE_DIR}/${stem}.png`;
    const meta = await sharp(path.join(root, file)).metadata();
    if (meta.width !== MASTER_SIZE || meta.height !== MASTER_SIZE) {
      throw new Error(`${file} must be ${MASTER_SIZE}x${MASTER_SIZE}, got ${meta.width}x${meta.height}`);
    }
    // iOS rejects app icons with an alpha channel.
    if (meta.hasAlpha) throw new Error(`${file} must not have transparency; flatten it onto its background`);
  }

  const margin = (MASTER_SIZE - GRID_CONTENT) / 2;
  const mask = Buffer.from(
    `<svg width="${GRID_CONTENT}" height="${GRID_CONTENT}"><rect width="${GRID_CONTENT}" height="${GRID_CONTENT}" rx="${GRID_RADIUS}" ry="${GRID_RADIUS}" fill="#fff"/></svg>`,
  );
  const render = {
    dock: async (source) => {
      const content = await sharp(source)
        .resize(GRID_CONTENT, GRID_CONTENT, { fit: 'cover' })
        .ensureAlpha()
        .composite([{ input: mask, blend: 'dest-in' }])
        .png()
        .toBuffer();
      const canvas = await sharp(content)
        .extend({ top: margin, bottom: margin, left: margin, right: margin, background: { r: 0, g: 0, b: 0, alpha: 0 } })
        .png()
        .toBuffer();
      return sharp(canvas).resize(DOCK_SIZE, DOCK_SIZE).png({ compressionLevel: 9 }).toBuffer();
    },
    preview: (source) =>
      sharp(source)
        .resize(PREVIEW_SIZE, PREVIEW_SIZE, { fit: 'cover' })
        .flatten({ background: '#ffffff' })
        .png({ compressionLevel: 9 })
        .toBuffer(),
  };

  const write = (file, data) => {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.writeFileSync(path.join(root, file), data);
  };
  const outputs = {};
  for (const { file, kind, source } of imageOutputs(icons)) {
    const data = await render[kind](path.join(root, source));
    write(file, data);
    outputs[file] = sha256(data);
  }
  for (const { file, text } of textOutputs(icons)) write(file, text);
  for (const file of stalePngs(root, icons)) fs.rmSync(path.join(root, file));

  const sources = Object.fromEntries(sourceFiles(icons).map((file) => [file, readSourceHash(root, file)]));
  write(RECORD, `${JSON.stringify({ sources, outputs }, null, 2)}\n`);
  return { icons, outputs: Object.keys(outputs).length + textOutputs(icons).length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  if (process.argv.includes('--check')) {
    const problems = checkAppIcons();
    if (problems.length > 0) {
      console.error(`[generate-app-icons] run \`pnpm generate:app-icons\`:\n${problems.map((line) => `  - ${line}`).join('\n')}`);
      process.exit(1);
    }
    console.log('[generate-app-icons] up to date');
  } else {
    const { icons, outputs } = await generate(repoRoot);
    console.log(`[generate-app-icons] ${icons.length} icons, ${outputs} files written`);
  }
}
