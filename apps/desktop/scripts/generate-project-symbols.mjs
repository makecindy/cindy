#!/usr/bin/env node
/**
 * generate-project-symbols.mjs — write the drawings of the project symbols
 * (PROJECT_SYMBOLS in packages/maker-shared/src/projectIcons.ts) into
 * packages/maker-shared/src/projectSymbolNodes.generated.ts.
 *
 * Desktop and Mobile render these shared drawings with their own Lucide
 * runtime, so adding a symbol is one line in PROJECT_SYMBOLS plus this
 * command; neither app keeps its own list.
 *
 * Usage (from the repository root): pnpm generate:project-symbols [--check]
 */
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const desktopDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(desktopDir, '../..');
const SOURCE = 'packages/maker-shared/src/projectIcons.ts';
const OUTPUT = 'packages/maker-shared/src/projectSymbolNodes.generated.ts';

const lf = (text) => text.replace(/\r\n/g, '\n');

function symbolNames(root) {
  const source = lf(fs.readFileSync(path.join(root, SOURCE), 'utf8'));
  const start = source.indexOf('export const PROJECT_SYMBOLS = [');
  const end = source.indexOf('] as const;', start);
  if (start < 0 || end < 0) throw new Error(`${SOURCE}: PROJECT_SYMBOLS not found`);
  const names = [...source.slice(start, end).matchAll(/\{\s*name:\s*"([A-Za-z0-9]+)"/g)].map((match) => match[1]);
  if (names.length === 0) throw new Error(`${SOURCE}: PROJECT_SYMBOLS is empty`);
  return names;
}

/** Lucide's file name for a component name: Gamepad2 -> gamepad-2. */
const kebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Za-z])([0-9])/g, '$1-$2')
    .toLowerCase();

/** The generated module, from the Lucide version Desktop is built with. */
export function projectSymbolSource(root = repoRoot) {
  const lucideDir = path.dirname(
    createRequire(path.join(desktopDir, 'package.json')).resolve('lucide-react/package.json'),
  );
  const { version } = JSON.parse(fs.readFileSync(path.join(lucideDir, 'package.json'), 'utf8'));
  const rows = symbolNames(root).map((name) => {
    const file = path.join(lucideDir, 'dist/esm/icons', `${kebab(name)}.js`);
    if (!fs.existsSync(file)) throw new Error(`${SOURCE}: Lucide ${version} has no icon named ${name}`);
    const module = fs.readFileSync(file, 'utf8');
    const match = module.match(/createLucideIcon\("[^"]+",\s*(\[[\s\S]*\])\s*\);/);
    if (!match) throw new Error(`Cannot read the drawing of ${name} from ${file}`);
    // The icon module holds a plain array literal of [tag, attributes] pairs.
    const node = new Function(`return ${match[1]};`)();
    return `  ${name}: ${JSON.stringify(node)},`;
  });
  return (
    '// Generated by `pnpm generate:project-symbols` from PROJECT_SYMBOLS in projectIcons.ts\n' +
    `// (Lucide ${version}, ISC License). Do not edit: change the list and run the command again.\n\n` +
    `export const PROJECT_SYMBOL_NODES = {\n${rows.join('\n')}\n} as const;\n`
  );
}

export function checkProjectSymbols(root = repoRoot) {
  const file = path.join(root, OUTPUT);
  const current = fs.existsSync(file) ? lf(fs.readFileSync(file, 'utf8')) : null;
  return current === projectSymbolSource(root) ? [] : [`${OUTPUT} is out of date`];
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  if (process.argv.includes('--check')) {
    const problems = checkProjectSymbols();
    if (problems.length > 0) {
      console.error(`[generate-project-symbols] run \`pnpm generate:project-symbols\`:\n${problems.map((line) => `  - ${line}`).join('\n')}`);
      process.exit(1);
    }
    console.log('[generate-project-symbols] up to date');
  } else {
    fs.writeFileSync(path.join(repoRoot, OUTPUT), projectSymbolSource());
    console.log(`[generate-project-symbols] wrote ${OUTPUT}`);
  }
}
