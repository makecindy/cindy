/**
 * Mission handoff: a zero-token snapshot of an unfinished Claude Code task, built only from
 * the local transcript JSONL. Lines here mirror the real CLI format (user / assistant / summary
 * entries, content blocks, usage).
 */
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

import {
  RESUME_CHEAP_THRESHOLD_TOKENS,
  buildMissionSnapshot,
  estimateTokens,
  planHandoff,
  readMissionSnapshotFile,
  renderMissionBrief,
} from '../handoff.js';

let n = 0;
const base = () => ({ uuid: `u${++n}`, sessionId: 'sess-1', cwd: 'D:\\proj', gitBranch: 'feat/x', isSidechain: false });

const user = (content: unknown, extra: Record<string, unknown> = {}) =>
  JSON.stringify({ ...base(), type: 'user', message: { role: 'user', content }, ...extra });
const assistant = (content: unknown[], usage?: Record<string, number>, extra: Record<string, unknown> = {}) =>
  JSON.stringify({ ...base(), type: 'assistant', message: { role: 'assistant', content, ...(usage ? { usage } : {}) }, ...extra });
const toolUse = (id: string, name: string, input: unknown) => ({ type: 'tool_use', id, name, input });
const toolResult = (id: string, content: string, isError = false) =>
  user([{ type: 'tool_result', tool_use_id: id, content, ...(isError ? { is_error: true } : {}) }]);

const USAGE = { input_tokens: 12, cache_creation_input_tokens: 3_000, cache_read_input_tokens: 61_000, output_tokens: 900 };

function typicalTranscript(): string[] {
  return [
    user('Build a login page with email + password and tests'),
    assistant([{ type: 'text', text: 'Plan first.' }, toolUse('t1', 'TodoWrite', {
      todos: [
        { content: 'Create form component', status: 'completed' },
        { content: 'Add validation', status: 'in_progress' },
        { content: 'Write tests', status: 'pending' },
      ],
    })]),
    toolResult('t1', 'ok'),
    assistant([toolUse('t2', 'Write', { file_path: 'D:\\proj\\src\\Login.tsx', content: '...' })]),
    toolResult('t2', 'written'),
    user('Also support "remember me"'),
    assistant([toolUse('t3', 'Edit', { file_path: 'D:\\proj\\src\\validate.ts', old_string: 'a', new_string: 'b' })]),
    toolResult('t3', 'String not found in file', true),
    assistant([{ type: 'text', text: 'Validation is half done; the email regex is in validate.ts.' }]),
    assistant([toolUse('t4', 'Bash', { command: 'pnpm test src/validate' })], USAGE),
  ];
}

describe('buildMissionSnapshot', () => {
  it('extracts goal, latest instructions, plan, progress, files, errors and interruption', () => {
    const s = buildMissionSnapshot(typicalTranscript());
    expect(s.sessionId).toBe('sess-1');
    expect(s.cwd).toBe('D:\\proj');
    expect(s.gitBranch).toBe('feat/x');
    expect(s.goal).toBe('Build a login page with email + password and tests');
    expect(s.recentInstructions).toEqual(['Also support "remember me"']);
    expect(s.todos).toEqual([
      { content: 'Create form component', status: 'completed' },
      { content: 'Add validation', status: 'in_progress' },
      { content: 'Write tests', status: 'pending' },
    ]);
    expect(s.lastProgress).toBe('Validation is half done; the email regex is in validate.ts.');
    expect(s.filesTouched).toEqual(['D:\\proj\\src\\Login.tsx', 'D:\\proj\\src\\validate.ts']);
    expect(s.recentErrors).toEqual(['Edit: String not found in file']);
    expect(s.interrupted).toEqual({ tool: 'Bash', detail: 'pnpm test src/validate' });
    expect(s.contextTokens).toBe(12 + 3_000 + 61_000);
    expect(s.userTurns).toBe(2);
  });

  it('ignores tool results, meta lines, slash-command echoes and sidechains as prompts', () => {
    const s = buildMissionSnapshot([
      user('<command-name>/clear</command-name>'),
      user('<local-command-stdout>done</local-command-stdout>'),
      user('Caveat: The messages below were generated by the user while running local commands.'),
      user('hidden meta', { isMeta: true }),
      user('subagent prompt', { isSidechain: true }),
      user([{ type: 'text', text: 'Real goal' }]),
      assistant([toolUse('s1', 'Write', { file_path: '/side.ts' })], undefined, { isSidechain: true }),
    ]);
    expect(s.goal).toBe('Real goal');
    expect(s.recentInstructions).toEqual([]);
    expect(s.filesTouched).toEqual([]);
  });

  it('keeps only errors after the latest user instruction, newest three', () => {
    const lines = [user('goal')];
    for (let i = 0; i < 5; i += 1) {
      lines.push(assistant([toolUse(`e${i}`, 'Bash', { command: `c${i}` })]), toolResult(`e${i}`, `fail ${i}`, true));
    }
    lines.push(user('try again'));
    lines.push(assistant([toolUse('e9', 'Bash', { command: 'c9' })]), toolResult('e9', 'fail 9', true));
    expect(buildMissionSnapshot(lines).recentErrors).toEqual(['Bash: fail 9']);
    expect(buildMissionSnapshot(lines.slice(0, -3)).recentErrors).toEqual(['Bash: fail 2', 'Bash: fail 3', 'Bash: fail 4']);
  });

  it('uses the latest compact summary and handles tool_result content arrays', () => {
    const s = buildMissionSnapshot([
      user('goal'),
      JSON.stringify({ type: 'summary', summary: 'old summary', leafUuid: 'x' }),
      user('This session is being continued... newer summary', { isCompactSummary: true }),
      assistant([toolUse('a', 'Read', { file_path: '/x' })]),
      user([{ type: 'tool_result', tool_use_id: 'a', is_error: true, content: [{ type: 'text', text: 'EACCES' }] }]),
    ]);
    expect(s.compactSummary).toBe('This session is being continued... newer summary');
    expect(s.recentErrors).toEqual(['Read: EACCES']);
    expect(s.interrupted).toBeUndefined();
  });

  it('survives garbage, blank and truncated lines', () => {
    const s = buildMissionSnapshot(['', 'not json', '{"type":"user"', 'null', '[]', user('goal')]);
    expect(s.goal).toBe('goal');
    expect(s.contextTokens).toBeNull();
  });

  it('returns an empty snapshot for an empty transcript', () => {
    const s = buildMissionSnapshot([]);
    expect(s).toMatchObject({ userTurns: 0, todos: [], filesTouched: [], recentErrors: [], contextTokens: null });
    expect(s.goal).toBeUndefined();
  });

  it('caps long fields and the file list', () => {
    const lines = [user('g'.repeat(5_000))];
    for (let i = 0; i < 60; i += 1) {
      lines.push(assistant([toolUse(`w${i}`, 'Write', { file_path: `/f${i}.ts` })]), toolResult(`w${i}`, 'ok'));
    }
    const s = buildMissionSnapshot(lines);
    expect(s.goal!.length).toBeLessThanOrEqual(1_500);
    expect(s.goal!.endsWith('…')).toBe(true);
    expect(s.filesTouched).toHaveLength(40);
    expect(s.filesTouched.at(-1)).toBe('/f59.ts');
  });
});

describe('readMissionSnapshotFile', () => {
  // Transcripts can be tens of MB; the file reader streams lines (CRLF too) and must give the
  // same snapshot as the in-memory parser.
  it('streams a real file to the same snapshot, including CRLF line endings', async () => {
    const dir = await mkdtemp(path.join(os.tmpdir(), 'cindy-handoff-'));
    try {
      const file = path.join(dir, 'sess-1.jsonl');
      await writeFile(file, `${typicalTranscript().join('\r\n')}\r\n`);
      expect(await readMissionSnapshotFile(file)).toEqual(buildMissionSnapshot(typicalTranscript()));
      await expect(readMissionSnapshotFile(path.join(dir, 'missing.jsonl'))).rejects.toMatchObject({ code: 'ENOENT' });
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });
});

describe('renderMissionBrief', () => {
  it('renders a self-contained brief that tells the agent to verify before redoing', () => {
    const brief = renderMissionBrief(buildMissionSnapshot(typicalTranscript()));
    expect(brief).toContain('# Continuing an unfinished task');
    expect(brief).toContain('check the current state');
    expect(brief).toContain('Build a login page');
    expect(brief).toContain('- [x] Create form component');
    expect(brief).toContain('- [~] Add validation');
    expect(brief).toContain('- [ ] Write tests');
    expect(brief).toContain('D:\\proj\\src\\validate.ts');
    expect(brief).toContain('Interrupted: Bash');
    expect(brief).toContain('Working directory: D:\\proj (branch feat/x)');
    expect(estimateTokens(brief)).toBeLessThan(3_000);
  });

  it('omits empty sections', () => {
    const brief = renderMissionBrief(buildMissionSnapshot([user('just a goal')]));
    expect(brief).toContain('just a goal');
    expect(brief).not.toContain('## Plan');
    expect(brief).not.toContain('## Open problems');
    expect(brief).not.toContain('Interrupted');
  });
});

describe('planHandoff', () => {
  it('recommends a brief when the context is large', () => {
    const plan = planHandoff(buildMissionSnapshot(typicalTranscript()));
    expect(plan.recommended).toBe('brief');
    expect(plan.resume.estimatedTokens).toBe(64_012);
    expect(plan.brief.estimatedTokens).toBe(estimateTokens(plan.brief.text));
    expect(plan.brief.estimatedTokens).toBeLessThan(plan.resume.estimatedTokens!);
  });

  it('recommends resume when the context is small or unknown', () => {
    const small = buildMissionSnapshot([
      user('goal'),
      assistant([{ type: 'text', text: 'hi' }], { input_tokens: 100, cache_creation_input_tokens: 0, cache_read_input_tokens: 0 }),
    ]);
    expect(planHandoff(small).recommended).toBe('resume');
    const unknown = buildMissionSnapshot([user('goal')]);
    expect(planHandoff(unknown).recommended).toBe('resume');
    expect(planHandoff(unknown).resume.estimatedTokens).toBeNull();
  });

  it('honours a custom threshold', () => {
    const s = buildMissionSnapshot(typicalTranscript());
    expect(planHandoff(s, { resumeThresholdTokens: 100_000 }).recommended).toBe('resume');
    expect(RESUME_CHEAP_THRESHOLD_TOKENS).toBe(40_000);
  });
});
