function regionForEndpoint(baseUrl?: string): 'beijing' | 'singapore' | undefined {
  if (!baseUrl) return undefined;
  const hostname = new URL(baseUrl).hostname;
  if (hostname === 'dashscope.aliyuncs.com') return 'beijing';
  if (hostname === 'dashscope-intl.aliyuncs.com') return 'singapore';
  const workspace = /^[a-z0-9-]+\.(cn-beijing|ap-southeast-1)\.maas\.aliyuncs\.com$/.exec(hostname);
  return workspace ? (workspace[1] === 'cn-beijing' ? 'beijing' : 'singapore') : undefined;
}

/** Unknown proxy locations retain the model's reference set, without guessing a
 * region or changing the selected connection. A reference never proves execution.
 */
export function alibabaSystemVoices(
  modelId: string,
  protocol: SpeechProtocol,
  baseUrl?: string,
): SpeechVoice[] {
  if (protocol !== (modelId === 'qwen3-tts-flash' ? 'qwen-tts' : 'dashscope-tts')) return [];
  const region = regionForEndpoint(baseUrl);
  return (SYSTEM_VOICES[modelId] ?? [])
    .filter(([, , onlyRegion]) => !region || !onlyRegion || region === onlyRegion)
    .map(([id, name]) => ({ id, name }));
}
