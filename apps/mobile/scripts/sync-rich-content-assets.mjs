import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, '../../..');
const mobileRoot = join(repositoryRoot, 'apps/mobile');
const generatedPath = join(mobileRoot, 'src/session/richContentAssets.generated.ts');

async function readPackageVersion(packageName) {
  const packageJsonPath = join(repositoryRoot, 'node_modules', packageName, 'package.json');
  const packageJson = JSON.parse(await readFile(packageJsonPath, 'utf8'));
  return packageJson.version;
}

async function buildKatexCss() {
  const katexRoot = join(repositoryRoot, 'node_modules/katex');
  let css = await readFile(join(katexRoot, 'dist/katex.min.css'), 'utf8');
  const fontDirectory = join(katexRoot, 'dist/fonts');
  const fontNames = await readdir(fontDirectory);
  const fontData = new Map();

  await Promise.all(fontNames.filter((name) => name.endsWith('.woff2')).map(async (name) => {
    const bytes = await readFile(join(fontDirectory, name));
    fontData.set(name, bytes.toString('base64'));
  }));

  css = css.replace(
    /,url\(fonts\/[^)]+\.woff\) format\("woff"\),url\(fonts\/[^)]+\.ttf\) format\("truetype"\)/g,
    '',
  );
  css = css.replace(/url\(fonts\/([^/()]+\.woff2)\)/g, (_, name) => {
    const base64 = fontData.get(name);
    if (!base64) throw new Error(`Missing KaTeX font asset: ${name}`);
    return `url(data:font/woff2;base64,${base64})`;
  });
  return css;
}

async function buildAssets() {
  const katexRoot = join(repositoryRoot, 'node_modules/katex');
  const mermaidRoot = join(repositoryRoot, 'node_modules/mermaid');
  const [katexVersion, mermaidVersion, katexJs, katexCss, mermaidJs] = await Promise.all([
    readPackageVersion('katex'),
    readPackageVersion('mermaid'),
    readFile(join(katexRoot, 'dist/katex.min.js'), 'utf8'),
    buildKatexCss(),
    readFile(join(mermaidRoot, 'dist/mermaid.min.js'), 'utf8'),
  ]);

  return `// This file is generated by apps/mobile/scripts/sync-rich-content-assets.mjs.\n// Do not edit it by hand; update the package versions and rerun the sync script.\n\nexport const MOBILE_KATEX_VERSION = ${JSON.stringify(katexVersion)};\nexport const MOBILE_KATEX_JS = ${JSON.stringify(katexJs)};\nexport const MOBILE_KATEX_CSS = ${JSON.stringify(katexCss)};\n\nexport const MOBILE_MERMAID_VERSION = ${JSON.stringify(mermaidVersion)};\nexport const MOBILE_MERMAID_JS = ${JSON.stringify(mermaidJs)};\n`;
}

await mkdir(dirname(generatedPath), { recursive: true });
await writeFile(generatedPath, await buildAssets());
console.log(`Synchronized Mobile rich-content assets at ${generatedPath}`);
