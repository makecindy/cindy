for (const flow of requiredFlows) {
  const fullPath = join(flowRoot, flow);
  if (!existsSync(fullPath)) {
    throw new Error(`Missing Maestro flow: ${flow}`);
  }
}

const allFlowText = requiredFlows
  .map((flow) => readFileSync(join(flowRoot, flow), 'utf8'))
  .join('\n');
for (const marker of requiredFlowMarkers) {
  if (!allFlowText.includes(marker)) {
    throw new Error(`Maestro flow smoke failed: missing marker "${marker}"`);
  }
}

const sourceText = listFiles(resolve(mobileRoot, 'app'))
  .concat(listFiles(resolve(mobileRoot, 'src')))
  .filter((file) => /\.(tsx?|jsx?)$/.test(file))
  .map((file) => readFileSync(file, 'utf8'))
  .join('\n');

for (const anchor of requiredSourceAnchors) {
  if (!sourceText.includes(anchor)) {
    throw new Error(`Maestro flow smoke failed: source is missing testID "${anchor}"`);
  }
}

const mockHostText = readFileSync(resolve(scriptDir, 'mock-device-link-host.mjs'), 'utf8');
if (!mockHostText.includes('MOCK_IMAGE_DATA_URL')) {
  throw new Error('Maestro flow smoke failed: mock host is missing the shared visual image fixture');
}
if (mockHostText.includes('iVBORw0KGgoAAAANSUhEUgAAAAEAAAAB')) {
  throw new Error('Maestro flow smoke failed: mock host visual image regressed to a 1x1 PNG');
}
if (!mockHostText.includes('iVBORw0KGgoAAAANSUhEUgAAAKAAAABa')) {
  throw new Error('Maestro flow smoke failed: mock host visual image is not the expected 160x90 PNG fixture');
}

console.log(`maestro-flow-smoke passed: ${requiredFlows.length} flow(s), ${requiredSourceAnchors.length} source anchors`);

function listFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const fullPath = join(dir, entry);
    if (statSync(fullPath).isDirectory()) {
      out.push(...listFiles(fullPath));
    } else {
      out.push(fullPath);
    }
  }
  return out;
}
